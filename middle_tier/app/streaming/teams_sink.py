# The real sink
# --------------------------------------------------------------------------

SendActivity = Callable[[Mapping[str, Any]], Awaitable[Any]]


class ConnectorTeamsSink:
    """Sends streaming activities through an injected transport.

    The transport is a single async callable ``send(activity) -> response``.
    Keeping the HTTP out of this class is what lets the renderer tests cover
    sequence numbering and the cumulative guard with no network at all,
    while the real deployment passes a Bot Connector POST.

    Transport failures are logged and swallowed for informative and content
    updates (losing a progress tick must not lose the answer) but are
    RE-RAISED for :meth:`final`, because a lost final message means the user
    never got an answer and the caller has to know.
    """

    def __init__(
        self,
        send: SendActivity,
        *,
        min_interval: float = TEAMS_MIN_UPDATE_INTERVAL_SECONDS,
        clock: Callable[[], float] | None = None,
        log: logging.Logger | None = None,
    ) -> None:
        self._send = send
        self._state = StreamState()
        self._window = _RateWindow(min_interval, clock=clock)
        self._log = log or logger
        self._lock = asyncio.Lock()  # serialise: never two in-flight requests
        self._last_content_sent = ""
        self._pending_content: str | None = None

    # -- introspection used by the renderer and by tests ----------------

    @property
    def state(self) -> StreamState:
        return self._state

    @property
    def last_content_sent(self) -> str:
        return self._last_content_sent

    # -- TeamsSink ------------------------------------------------------

    async def informative(self, text: str) -> None:
        text = (text or "").strip()
        if not text:
            return
        if self._state.closed:
            self._log.debug("informative update after stream close; ignoring")
            return
        if self._state.content_started:
            # Documented: after the first content chunk, informative updates
            # no longer display. Sending them anyway just burns throttle
            # budget that the content updates need.
            self._log.debug("informative update after content started; skipping")
            return
        if len(text) > TEAMS_INFORMATIVE_MAX_CHARS:
            text = text[: TEAMS_INFORMATIVE_MAX_CHARS - 3] + "..."

        async with self._lock:
            if not self._window.is_open():
                # An informative update is pure status; a stale one is worth
                # nothing, so drop rather than queue.
                self._log.debug("throttled: dropping informative update %r", text)
                return
            await self._dispatch(text, STREAM_TYPE_INFORMATIVE)

    async def content(self, cumulative_text: str) -> None:
        cumulative_text = cumulative_text or ""
        if not cumulative_text:
            return
        if self._state.closed:
            self._log.debug("content update after stream close; ignoring")
            return

        self._assert_cumulative(cumulative_text)

        async with self._lock:
            if not self._window.is_open():
                # Coalesce. Safe ONLY because updates are cumulative.
                self._pending_content = cumulative_text
                self._log.debug(
                    "throttled: coalescing content update (%d chars pending)",
                    len(cumulative_text),
                )
                return
            self._pending_content = None
            await self._dispatch(cumulative_text, STREAM_TYPE_STREAMING)

    async def final(self, text: str) -> None:
        if self._state.closed:
            self._log.debug("final activity sent twice; ignoring the second")
            return
        text = text or ""
        if text:
            self._assert_cumulative(text)

        async with self._lock:
            self._pending_content = None
            # The final message is not optional and is not throttle-skippable.
            # Wait out the window rather than drop it.
            delay = self._window.seconds_until_open()
            if delay > 0:
                await asyncio.sleep(delay)
            activity = build_activity(
                text=text,
                stream_type=STREAM_TYPE_FINAL,
                stream_id=self._state.stream_id,
                sequence=None,  # docs: must NOT be set on the final message
            )
            response = await self._send(activity)
            self._state.adopt_stream_id(response)
            self._window.mark_sent()
            self._state.closed = True
            self._last_content_sent = text

    async def flush(self) -> None:
        """Send any coalesced content update. Optional; :meth:`final` also flushes."""
        pending = self._pending_content
        if pending is None or self._state.closed:
            return
        async with self._lock:
            if self._pending_content is None or self._state.closed:
                return
            delay = self._window.seconds_until_open()
            if delay > 0:
                await asyncio.sleep(delay)
            pending = self._pending_content
            self._pending_content = None
            await self._dispatch(pending, STREAM_TYPE_STREAMING)

    # -- internals ------------------------------------------------------

    def _assert_cumulative(self, text: str) -> None:
        previous = self._last_content_sent
        if previous and not text.startswith(previous):
            raise CumulativeContractViolation(
                "Teams streamed updates are cumulative: this update does not "
                "contain everything already streamed. Previously sent "
                f"{len(previous)} chars, this update starts differently. "
                "See app/streaming/README.md."
            )

    async def _dispatch(self, text: str, stream_type: str) -> None:
        activity = build_activity(
            text=text,
            stream_type=stream_type,
            stream_id=self._state.stream_id,
            sequence=self._state.next_sequence(),
        )
        try:
            response = await self._send(activity)
        except Exception:
            # A dropped progress update is a cosmetic failure. Log it and
            # keep the turn alive; the final message still carries the whole
            # answer because the protocol is cumulative.
            self._log.warning(
                "failed to send %s streaming activity; continuing", stream_type, exc_info=True
            )
            self._window.mark_sent()
            return
        self._state.adopt_stream_id(response)
        self._state.opened = True
        self._window.mark_sent()
        if stream_type == STREAM_TYPE_STREAMING:
            self._state.content_started = True
            self._last_content_sent = text


