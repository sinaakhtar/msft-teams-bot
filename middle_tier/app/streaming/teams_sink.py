class RecordingTeamsSink:
    """A :class:`TeamsSink` that records instead of sending. No network.

    Lives in production code rather than in the test file on purpose: the
    turn handler, the renderer tests and anyone debugging a stream all want
    the same fake, and three divergent copies of it is how a test double
    stops matching the thing it doubles.

    Enforces the cumulative contract on every content update, so a
    regression fails loudly in any test that uses it, not only in the tests
    that explicitly assert on it.
    """

    def __init__(self, *, enforce_cumulative: bool = True) -> None:
        self.informative_updates: list[str] = []
        self.content_updates: list[str] = []
        self.final_text: str | None = None
        self.calls: list[tuple[str, str]] = []  # (kind, text) in real order
        self.send_times: list[float] = []
        self._enforce = enforce_cumulative

    async def informative(self, text: str) -> None:
        self.informative_updates.append(text)
        self.calls.append(("informative", text))
        self.send_times.append(time.monotonic())

    async def content(self, cumulative_text: str) -> None:
        if self._enforce and self.content_updates:
            previous = self.content_updates[-1]
            if not cumulative_text.startswith(previous):
                raise CumulativeContractViolation(
                    f"update {cumulative_text!r} does not contain previous {previous!r}"
                )
        self.content_updates.append(cumulative_text)
        self.calls.append(("content", cumulative_text))
        self.send_times.append(time.monotonic())

    async def final(self, text: str) -> None:
        self.final_text = text
        self.calls.append(("final", text))
        self.send_times.append(time.monotonic())


